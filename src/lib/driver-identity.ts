import AsyncStorage from '@react-native-async-storage/async-storage';

const DRIVER_ID_KEY = '@eva:driverId';

/**
 * Returns the persistent anonymous driverId for this device.
 *
 * On first launch: generates a UUID v4, stores it in AsyncStorage.
 * On subsequent launches: reads and returns the stored UUID.
 *
 * This UUID is the user's identity across all sessions on this device.
 * It matches the users.id UUID in Supabase.
 *
 * Recovery: if the user signs in via Google (Week 3+), the server maps
 * the Google account to this UUID and merges any prior anonymous memory.
 * On app reinstall (UUID lost), Google Sign-In restores the correct UUID.
 * Anonymous users with no auth have no recovery path — by design.
 */
export async function getOrCreateDriverId(): Promise<string> {
  try {
    const stored = await AsyncStorage.getItem(DRIVER_ID_KEY);
    if (stored) {
      return stored;
    }
    // First launch — generate and persist
    const newId = generateUUID();
    await AsyncStorage.setItem(DRIVER_ID_KEY, newId);
    console.log(`[driver-identity] New anonymous driver ID created: ${newId}`);
    return newId;
  } catch (err) {
    // AsyncStorage failure — generate ephemeral ID for this session
    console.error('[driver-identity] AsyncStorage error:', err);
    return generateUUID();
  }
}

/**
 * Clears the stored driverId. Use only for testing or explicit sign-out.
 * Calling this means the next session starts as a new anonymous user.
 */
export async function clearDriverId(): Promise<void> {
  await AsyncStorage.removeItem(DRIVER_ID_KEY);
}

/**
 * RFC 4122 UUID v4 — matches the format generated by the server's uuidv4().
 * Not using a library to keep the mobile bundle lean.
 */
function generateUUID(): string {
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, c => {
    const r = (Math.random() * 16) | 0;
    const v = c === 'x' ? r : (r & 0x3) | 0x8;
    return v.toString(16);
  });
}
